#!/usr/bin/env python3
"""Generate tests/qcom-tee/fake-scm: the REAL android-7.3 qcom-scm.ko sources
(qcom_scm.c, qcom_scm-smc.c, qcom_scm-legacy.c, qcom_tzmem.c + private headers)
with only the two SMC instruction call sites redirected to avr_fake_tz.c.

QEMU has no TrustZone. Everything above the SMC instruction (SCM descriptor
encoding, convention probing, SHM bridge registry, TZMEM pools, the restored
vendor SMCInvoke wrappers, si_core, smcinvoke) runs unmodified; exports keep
their CRCs because types and config are identical. QEMU-only, never shipped.
"""
from pathlib import Path
import shutil, subprocess, sys
ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT.parent / 'avr-upstream-audit/android-7.3/drivers/firmware/qcom'
OUT = Path(__file__).resolve().parent / 'fake-scm'
OUT.mkdir(exist_ok=True)
for f in ['qcom_scm.c', 'qcom_scm-smc.c', 'qcom_scm-legacy.c', 'qcom_tzmem.c']:
    s = (SRC / f).read_text()
    if f == 'qcom_scm-smc.c':
        assert s.count('arm_smccc_smc_quirk(') == 1
        s = s.replace('arm_smccc_smc_quirk(', 'avr_fake_smc_quirk(', 1)
        s = '#include "avr_fake_tz.h"\n' + s
    if f == 'qcom_scm-legacy.c':
        n = s.count('arm_smccc_smc(')
        assert n == 2, n
        s = s.replace('arm_smccc_smc(', 'avr_fake_smc(')
        s = '#include "avr_fake_tz.h"\n' + s
    (OUT / f).write_text(s)
for h in SRC.glob('*.h'):
    shutil.copy(h, OUT / h.name)
HERE = Path(__file__).resolve().parent
for f in ['avr_fake_tz.c', 'avr_fake_tz.h']:
    shutil.copy(HERE / f, OUT / f)
(OUT / 'Makefile').write_text('# generated by prepare_fake_scm.py (QEMU-only)\nobj-m += qcom-scm.o\nqcom-scm-objs := qcom_scm.o qcom_scm-smc.o qcom_scm-legacy.o qcom_tzmem.o avr_fake_tz.o\nCFLAGS_qcom_scm-smc.o := -I$(src)\nccflags-y += -I$(src)\n')
commit = subprocess.check_output(['git', '-C', str(SRC), 'rev-parse', 'HEAD'], text=True).strip()
(OUT / 'SOURCE_COMMIT').write_text(commit + '\n')
print('fake-scm generated from android-7.3', commit)
