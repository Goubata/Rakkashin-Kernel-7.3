#!/usr/bin/env python3
"""Create/refresh a port from qcom-soc (037aa1c) modules.bzl registrations.
Usage: gen_qcom_soc_port.py <port-dir-name> <module> [<module> ...]
  module = output name without .ko (dashes or underscores).
Copies srcs (+ conditional_srcs enabled by canoe_perf.bzl), the vendor headers they
include from qcom-soc/include that 7.3 lacks (recursively), writes Makefile with the
module's config as a define (vendor CONFIGs come from avr-canoe-vendor-config.h via
scripts/parity_build.sh), and source-spec.json."""
import json, re, shutil, subprocess, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
Q = ROOT.parent / 'avr-upstream-audit/qcom-soc'
A = ROOT.parent / 'avr-upstream-audit/android-7.3'
port, mods = sys.argv[1], [m.replace('_', '-') for m in sys.argv[2:]]
D = ROOT / 'ports' / port
D.mkdir(parents=True, exist_ok=True)
canoe = dict(re.findall(r'"(CONFIG_\w+)":\s*"(\w+)"', (Q / 'configs/canoe_perf.bzl').read_text()))
regs = {}
for b in Q.rglob('modules.bzl'):
    t = b.read_text()
    for m in re.finditer(r'registry\.register\((.*?)\n    \)', t, re.S):
        body = m.group(1)
        out = re.search(r'out = "([\w-]+)\.ko"', body)
        if out:
            regs[out.group(1)] = body
K73 = ROOT.parent / 'avr-upstream-audit/android-7.3'
PATCHED = {}
for _m in re.finditer(r'"//common:([\w/.+-]+)",\s*":([\w/.+-]+\.diff)",\s*\],\s*outs = \["([\w/.+-]+)"\]',
                      (Path(__file__).resolve().parents[2] / 'avr-upstream-audit/qcom-soc/common_sources.bzl').read_text()):
    PATCHED[_m.group(3)] = (_m.group(1), _m.group(2))


def norm(n):
    for k in regs:
        if k.replace('-', '_') == n.replace('-', '_'):
            return k
    raise SystemExit('no registration for ' + n)
files, mk = {}, ['# SPDX-License-Identifier: GPL-2.0-only',
                 f'# Generated by scripts/gen_qcom_soc_port.py from qcom-soc 037aa1c modules.bzl ({port})']
defs = set()
for mod in mods:
    k = norm(mod)
    body = regs[k]
    cfg = re.search(r'config = "(CONFIG_\w+)"', body)
    if cfg:
        defs.add(f'-D{cfg.group(1)}_MODULE=1')
    srcs = re.findall(r'"([\w/.+-]+\.[ch])"', body[:body.index('deps') if 'deps' in body else len(body)].split('conditional_srcs')[0])
    if 'conditional_srcs' in body:
        cs = body[body.index('conditional_srcs'):]
        for c in re.finditer(r'"(CONFIG_\w+)":\s*\{(.*?)\n\s*\},', cs, re.S):
            on = canoe.get(c.group(1)) in ('y', 'm')
            sel = re.search(('True' if on else 'False') + r':\s*\[(.*?)\]', c.group(2), re.S)
            if sel:
                srcs += re.findall(r'"([\w/.+-]+\.[ch])"', sel.group(1))
    objs = []
    for s in srcs:
        rel = s
        dst = D / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        if not dst.exists():  # keep reviewed port edits on regeneration
            if (Q / s).exists():
                shutil.copy2(Q / s, dst)
            elif s in PATCHED:  # common_sources.bzl genrule: 7.3 file + vendor diff
                base, diff = PATCHED[s]
                shutil.copy2(K73 / base, dst)
                subprocess.run(['patch', '-s', '--no-backup-if-mismatch', str(dst), '-i', str(Q / diff)], check=True)
            elif (K73 / s).exists():  # COPY_FILES from //common, taken from 7.3
                shutil.copy2(K73 / s, dst)
            else:
                raise SystemExit(f'missing source {s}')
        files[str(dst.relative_to(ROOT))] = s
        if s.endswith('.c'):
            objs.append(s[:-2] + '.o')
    name = k
    if len(objs) > 1:  # kbuild: an object may not share the composite module's name
        for i, o in enumerate(objs):
            if Path(o).stem == name:
                w = Path(o).with_name(name + '_core.c')
                (D / w).write_text(f'// SPDX-License-Identifier: GPL-2.0-only\n'
                                   f'/* AVR: composite module {name}.ko cannot contain {name}.o */\n'
                                   f'#include "{name}.c"\n')
                objs[i] = str(w.with_suffix('.o'))
    mk.append(f'obj-m += {name}.o')
    if not (len(objs) == 1 and Path(objs[0]).stem == name and Path(objs[0]).parent == Path('.')):
        mk.append(f'{name}-y := ' + ' '.join(objs))
    copts = re.search(r'copts\s*=\s*\[(.*?)\]', body, re.S)
    if copts:
        flags = ' '.join(re.findall(r'"([^"]+)"', copts.group(1)))
        for o in objs:
            mk.append(f'CFLAGS_{o} += {flags}')
# vendor headers missing from 7.3
uses_walt = False
uses_gunyah = False
todo = [D / f for f in list(files.values())]
seen = set()
while todo:
    f = todo.pop()
    src = Q / f.relative_to(D) if str(f).startswith(str(D)) and (Q / f.relative_to(D)).exists() else f
    if not src.exists():
        continue
    text = src.read_text(errors='ignore')
    incs = re.findall(r'#\s*include\s*<([\w/.,+-]+)>', text)
    if str(src).startswith(str(Q / 'include')):  # "x.h" next to a vendor header
        here = src.parent.relative_to(Q / 'include')
        incs += [str(here / i) for i in re.findall(r'#\s*include\s*"([\w/.,+-]+)"', text)]
    for inc in incs:
        if inc in seen:
            continue
        seen.add(inc)
        if inc == 'linux/sched/walt.h':  # use the sched-walt port's header
            uses_walt = True
            continue
        if inc.startswith('linux/gunyah'):  # use the gunyah/gunyah-rm ports' headers
            uses_gunyah = True
            continue
        qv, av = Q / 'include' / inc, A / 'include' / inc
        if qv.exists() and not av.exists():
            dst = D / 'include' / inc
            dst.parent.mkdir(parents=True, exist_ok=True)
            if not dst.exists():
                # prefer a copy already adapted to 7.3 in another port
                prev = sorted(x for x in (ROOT / 'ports').glob('*/include/' + inc) if x.parts[-len(Path(inc).parts) - 3] != port)
                shutil.copy2(prev[0] if prev else qv, dst)
                if prev:
                    print('reused adapted header', prev[0].relative_to(ROOT))
            files[str(dst.relative_to(ROOT))] = 'include/' + inc
            todo.append(qv)
        elif qv.exists() and av.exists() and qv.read_bytes() != av.read_bytes():
            print('SHADOWED (7.3 header differs):', inc)
dirs = sorted({str(Path(s).parent) for s in files.values() if s.endswith('.h') and not s.startswith('include/')})
mk += ['ccflags-y += ' + ' '.join(sorted(defs)) + ' -Wno-missing-prototypes',
       'ccflags-y += -I$(src)/include -I$(src)/include/uapi -I$(srctree) ' + ' '.join(f'-I$(src)/{d}' for d in dirs),
       'ccflags-y += -include $(src)/avr-canoe-vendor-config.h']
if uses_gunyah:
    mk += ['ccflags-y += -I$(src)/../gunyah/include -I$(src)/../gunyah-rm/include']
if uses_walt:
    mk += ['ccflags-y += -I$(src)/../sched-walt/include -DCONFIG_SCHED_WALT_NR_CPUS=8',
           'KBUILD_EXTRA_SYMBOLS += $(src)/../sched-walt/Module.symvers']
mkf = D / 'Makefile'
if mkf.exists() and '# vendor CONFIG parity' in mkf.read_text():
    print('Makefile exists with local edits; not overwritten')
else:
    mkf.write_text('\n'.join(mk) + '\n')
cfgh = D / 'avr-canoe-vendor-config.h'
if not cfgh.exists():
    cfgh.write_text('')
files['ports/' + port + '/Makefile'] = None
commit = subprocess.check_output(['git', '-C', str(Q), 'rev-parse', 'HEAD'], text=True).strip()
spec = {'name': port, 'repo': 'qcom-soc', 'commit': commit, 'files': files,
        'scope': ' '.join(mods) + ' on android18-7.3', 'reviewed_changes': [], 'pending': ['phone']}
sp = D / 'source-spec.json'
if sp.exists():
    old = json.loads(sp.read_text())
    spec['reviewed_changes'] = old.get('reviewed_changes', [])
sp.write_text(json.dumps(spec, indent=1) + '\n')
print(port, len(mods), 'modules,', len(files), 'files')
