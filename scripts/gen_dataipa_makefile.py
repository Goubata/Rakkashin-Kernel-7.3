#!/usr/bin/env python3
"""Generate ports/dataipa/Makefile.generated from define_modules.bzl (gsim, ipam,
ipanetm ddk_modules, non-niobe/seraph branch) with the perf defconfig
(config/dataipa_GKI.conf) deciding conditional_srcs, like the DDK build."""
import re
from pathlib import Path
D = Path(__file__).resolve().parents[1] / 'ports/dataipa'
bzl = (D / 'define_modules.bzl').read_text()
conf = {}
for l in (D / 'config/dataipa_GKI.conf').read_text().splitlines():
    m = re.match(r'(?:export\s+)?(CONFIG_\w+)=(\w+)', l.strip())
    if m:
        conf[m.group(1)] = m.group(2)
opts = {k for k, v in conf.items() if v in ('y', 'm')}
out = ['# Generated by scripts/gen_dataipa_makefile.py (perf defconfig: config/dataipa_GKI.conf)', '']
for mod in ('gsim', 'ipam', 'ipanetm'):
    i = bzl.index(f'out = "{mod}.ko"')
    j = bzl.index('ddk_module(', i) if 'ddk_module(' in bzl[i:] else len(bzl)
    blk = bzl[i:j]
    srcs_blk = blk[blk.index('srcs = ['):blk.index(']', blk.index('srcs = ['))]
    srcs = [s for s in re.findall(r'"([^"]+\.c)"', srcs_blk)]
    if 'conditional_srcs' in blk:
        cs = blk[blk.index('conditional_srcs'):]
        for m in re.finditer(r'"(CONFIG_\w+)":\s*\{\s*True:\s*\[(.*?)\]', cs, re.S):
            if m.group(1) in opts:
                srcs += re.findall(r'"([^"]+\.c)"', m.group(2))
    out.append(f'obj-m += {mod}.o')
    out.append(f'{mod}-y := ' + ' '.join(s[:-2] + '.o' for s in dict.fromkeys(srcs)))
out.append('AVR_IPA_DEFINES := ' + ' '.join(f'-D{k}_MODULE=1' if conf[k] == 'm' else f'-D{k}=1' for k in sorted(opts)))
(D / 'Makefile.generated').write_text('\n'.join(out) + '\n')
print({m: len(re.findall(r'\.o', l)) for m, l in zip(('gsim','ipam','ipanetm'), [x for x in out if '-y :=' in x])})
