#!/usr/bin/env python3
"""Regenerate ports/<port>/avr-canoe-vendor-config.h (default port: msm-drm):
canoe_perf.bzl y/m options referenced by the port sources, the vendor headers on
its include path or any header a previous build included (.o.cmd), that are
absent from out/native-gki/.config and from the -D defines of the Makefile(s).
Usage: gen_drm_vendor_config.py [port]"""
import re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
D = ROOT / 'ports' / (sys.argv[1] if len(sys.argv) > 1 else 'msm-drm')
mk = ''.join(f.read_text() for f in D.glob('Makefile*'))
defs = set(re.findall(r'-D(CONFIG_[A-Z0-9_]+)', mk))
dirs = [x for x in D.iterdir() if x.is_dir()] + [D / d for d in re.findall(r'-I\$\(src\)/(\.\./[\w./-]+)', mk)]
ref = set()
files = set()
for d in dirs:
    files |= set(d.rglob('*.h')) | set(d.rglob('*.c')) if d.is_dir() else set()
# every header actually included by a previous build (kernel headers too: e.g.
# llcc-qcom.h / rpmh.h stub out their API unless CONFIG_QCOM_LLCC/RPMH is set)
SRC = ROOT.parent / 'avr-upstream-audit/android-7.3'
for cmd in D.rglob('.*.o.cmd'):
    txt = cmd.read_text(errors='ignore')
    for tok in re.findall(r'(/work/avr-(?:src|port)/[^\s:\\]+\.h)', txt):
        files.add(Path(tok.replace('/work/avr-src', str(SRC)).replace('/work/avr-port', str(ROOT))))
    # headers found through relative -I$(src)/../<port>/include paths
    for tok in re.findall(r'(?<![\w/])((?:\./)*\.\./[^\s:\\]+\.h)', txt):
        files.add((D / tok).resolve())
for f in files:
    if f.is_file():
        ref |= {c[:-7] if c.endswith('_MODULE') else c for c in re.findall(r'CONFIG_[A-Z0-9_]+', f.read_text(errors='ignore'))}
v = dict(re.findall(r'"(CONFIG_[A-Z0-9_]+)":\s*"(y|m)"', (ROOT.parent / 'avr-upstream-audit/qcom-soc/configs/canoe_perf.bzl').read_text()))
ours = set(re.findall(r'^(CONFIG_[A-Z0-9_]+)=[ym]', (ROOT / 'out/native-gki/.config').read_text(), re.M))
need = sorted(n for n in ref & set(v) if n not in ours and n not in defs)
lines = ['/* SPDX-License-Identifier: GPL-2.0-only */',
         "/* AVR 7.3: vendor (qcom-soc configs/canoe_perf.bzl) options that the phone's",
         ' * module was compiled with through the vendor kernel autoconf but that the 7.3',
         ' * GKI .config does not carry. Only options referenced by the sources or headers',
         ' * it includes are listed; all providers are ported modules. Generated by',
         ' * scripts/gen_drm_vendor_config.py from canoe_perf.bzl. */',
         '#ifndef AVR_CANOE_VENDOR_CONFIG_H', '#define AVR_CANOE_VENDOR_CONFIG_H']
lines += [f'#define {n}_MODULE 1' if v[n] == 'm' else f'#define {n} 1' for n in need]
lines.append('#endif')
(D / 'avr-canoe-vendor-config.h').write_text('\n'.join(lines) + '\n')
print(len(need), 'options')
