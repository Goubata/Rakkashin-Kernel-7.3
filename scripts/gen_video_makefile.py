#!/usr/bin/env python3
"""Generate ports/video-driver/Makefile.generated: msm_video from video_modules.bzl
with the canoe config_options of video_driver_build.bzl (MSM_MMRM, MSM_VIDC_LLCC,
MSM_VIDC_ANDROID, MSM_VIDC_MINIDUMP, MSM_VIDC_CANOE, MSM_VIDC_CHORA); includes =
video_driver_headers (BUILD.bazel)."""
import re
from pathlib import Path
D = Path(__file__).resolve().parents[1] / 'ports/video-driver'
mods = {}
class Reg:
    def register(self, name, path=None, config_option=None, srcs=(), config_srcs=None, deps=(), config_deps=None):
        mods[name] = dict(srcs=list(srcs), cs={k: ({True: v} if isinstance(v, list) else v) for k, v in (config_srcs or {}).items()}, opt=config_option)
src = '\n'.join(l for l in (D / 'video_modules.bzl').read_text().splitlines() if not l.startswith('load('))
exec(src, {'video_module_entry': lambda hdrs=None: Reg()})
b = (D / 'video_driver_build.bzl').read_text()
blk = b[b.index('elif target == "canoe":'):]
blk = blk[:blk.index('elif target in')]
opts = set(re.findall(r'"(CONFIG_\w+)"', blk)) | {'CONFIG_MSM_VIDC_CANOE', 'CONFIG_MSM_VIDC_CHORA'}
opts = {o for o in opts if '{' not in o}
m = mods['msm_video']
srcs = list(m['srcs'])
for k, sel in m['cs'].items():
    srcs += sel.get(k in opts, [])
bz = (D / 'BUILD.bazel').read_text()
inc = re.findall(r'includes = \[([^\]]*)\]', bz)
incs = []
for i in inc:
    incs += re.findall(r'"([^"]+)"', i)
out = ['# Generated by scripts/gen_video_makefile.py', 'obj-m += msm_video.o',
       'msm_video-y := ' + ' '.join(s[:-2] + '.o' for s in dict.fromkeys(srcs) if (D / s).is_file()),  # bzl uses native.glob
       'AVR_VIDEO_DEFINES := ' + ' '.join(f'-D{o}=1' for o in sorted(opts)),
       'AVR_VIDEO_INCLUDES := ' + ' '.join(f'-I$(src)/{i}' for i in dict.fromkeys(incs))]
(D / 'Makefile.generated').write_text('\n'.join(out) + '\n')
print(len(srcs), sorted(opts))
