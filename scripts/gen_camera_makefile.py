#!/usr/bin/env python3
"""Generate ports/camera-kernel/Makefile.generated from camera_modules.bzl for
canoe: options = project_defconfig.bzl common_configs + canoe dependency/project
configs + Kconfig 'default y if' (SPECTRA_SECURE_MINK_API); srcs = srcs +
conditional_srcs[enabled]; includes = BUILD.bazel driver_includes + uapi."""
import re
from pathlib import Path
D = Path(__file__).resolve().parents[1] / 'ports/camera-kernel'
pd = (D / 'project_defconfig.bzl').read_text()
common = re.findall(r'"(CONFIG_\w+)=y"', pd[pd.index('common_configs'):pd.index('dependency_config')])
dep = re.findall(r'"(CONFIG_\w+)=y"', pd[pd.index('dependency_config'):pd.index('project_configs')])
canoe = re.findall(r'"(CONFIG_\w+)=y"', pd[pd.index('":canoe"'):pd.index('})', pd.index('":canoe"'))])
opts = set(common) | set(dep) | set(canoe)
if opts & {'CONFIG_SPECTRA_DOMAIN_ID_SECURE_CAMERA', 'CONFIG_SPECTRA_SECURE_CAMERA_25'}:
    opts.add('CONFIG_SPECTRA_SECURE_MINK_API')
bzl = (D / 'camera_modules.bzl').read_text()
blk = bzl[bzl.index('name = "{}_camera".format(tv)'):]
blk = blk[:blk.index('copts =')]
srcs = re.findall(r'"([\w/.-]+\.c)"', blk[:blk.index('conditional_srcs')])
cs = blk[blk.index('conditional_srcs'):]
for m in re.finditer(r'"(CONFIG_\w+)":\s*\{(.*?)\n\s*\},', cs, re.S):
    body = re.sub(r'#[^\n]*', '', m.group(2))
    key = 'True' if m.group(1) in opts else 'False'
    sel = re.search(key + r':\s*\[(.*?)\]', body, re.S)
    if sel:
        srcs += re.findall(r'"([\w/.-]+\.c)"', sel.group(1))
inc = re.findall(r'"(drivers[\w/.-]*)"', (D / 'BUILD.bazel').read_text()[(D / 'BUILD.bazel').read_text().index('driver_includes'):])
out = ['# Generated by scripts/gen_camera_makefile.py (canoe options: ' + ' '.join(sorted(opts)) + ')',
       'obj-m += camera.o',
       'camera-y := ' + ' '.join(s[:-2] + '.o' for s in dict.fromkeys(srcs)),
       'AVR_CAMERA_DEFINES := ' + ' '.join(f'-D{o}=1' for o in sorted(opts)),
       'AVR_CAMERA_INCLUDES := ' + ' '.join(f'-I$(src)/{i}' for i in dict.fromkeys(inc) if (D / i).is_dir())]
(D / 'Makefile.generated').write_text('\n'.join(out) + '\n')
print(len(srcs), 'srcs', len(opts), 'opts')
