#!/usr/bin/env python3
"""Generate ports/audio-kernel/Makefile from the vendor audio_modules.bzl and the
'avr' branch of build/canoe.bzl, mirroring module_mgr.bzl: options = canoe
config_options + config_option of every enabled module; srcs = srcs +
conditional_srcs[option enabled]; local_defines = options."""
import re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
D = ROOT / 'ports/audio-kernel'
mods = {}
class Reg:
    def register(self, name, path=None, config_option=None, srcs=(), conditional_srcs=None, deps=()):
        cs = {}
        for k, v in (conditional_srcs or {}).items():
            cs[k] = {True: v} if isinstance(v, list) else v
        mods[name] = dict(path=path, config_option=config_option, srcs=list(srcs), cs=cs)
src = (D / 'audio_modules.bzl').read_text()
src = '\n'.join(l for l in src.splitlines() if not l.startswith('load('))
g = {'create_module_registry': lambda hdrs=None: Reg()}
exec(src, g)
canoe = (D / 'canoe.bzl').read_text()
blk = canoe[canoe.index('mmi_product_name in ["avr", "eletre"]'):]
blk = blk[:blk.index('  else:')]
modules = re.findall(r'"(\w+_dlkm)"', blk[:blk.index('config_options')])
opts = re.findall(r'"(CONFIG_\w+)"', blk[blk.index('config_options'):])
options = set(opts) | {mods[m]['config_option'] for m in modules if mods[m]['config_option']}
lines = ['# SPDX-License-Identifier: GPL-2.0-only',
         '# Generated by scripts/gen_audio_makefile.py from audio_modules.bzl + build/canoe.bzl',
         '# (mmi_product_name "avr"). Do not edit; edit the generator.', '']
seen = {}
for m in modules:
    info = mods[m]
    s = list(info['srcs'])
    for opt, sel in info['cs'].items():
        s += sel.get(opt in options, [])
    pre = info['path'] + '/' if info['path'] else ''
    objs = []
    for x in s:
        if not x.endswith('.c'):
            continue
        o = pre + x[:-2] + '.o'
        if o not in objs:
            objs.append(o)
    if not objs:
        continue
    for o in objs:
        seen.setdefault(o, []).append(m)
    lines.append(f'obj-m += {m}.o')
    lines.append(f'{m}-y := ' + ' '.join(objs))
dups = {o: ms for o, ms in seen.items() if len(ms) > 1}
lines.append('')
lines.append('AVR_AUDIO_DEFINES := ' + ' '.join(f'-D{o}=1' for o in sorted(options)))
(D / 'Makefile.generated').write_text('\n'.join(lines) + '\n')
print(len(modules), 'modules,', len(options), 'options; shared objects:', dups)
